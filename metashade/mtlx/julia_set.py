"""
A procedural Julia set node, generated as a MaterialX source-code node.

The node colors the Julia set of ``z^2 + c`` at the object-space position
projected along Z.  Time-dependent animation stays in the material graph,
which drives the ``cx``, ``cy`` and ``phase`` inputs.
"""

from __future__ import annotations

from dataclasses import dataclass

from metashade.mtlx.generate import GeneratorContext

FUNC_NAME = 'mx_julia_set'
NODEDEF_NAME = 'ND_julia_set'


@dataclass(frozen=True)
class _Input:
    doc: str
    default_value: str = ''
    defaultgeomprop: str = ''


_INPUTS = {
    'position': _Input(
        doc='Position sampled in the XY plane; Z is ignored.',
        defaultgeomprop='Pobject',
    ),
    'cx': _Input(doc='Real part of the constant c.', default_value='-0.74543'),
    'cy': _Input(
        doc='Imaginary part of the constant c.', default_value='0.11301'
    ),
    'scale': _Input(
        doc='Extent of the complex plane mapped to a unit of position.',
        default_value='3.0',
    ),
    'max_iterations': _Input(
        doc='Maximum number of iterations of z^2 + c.',
        default_value='64',
    ),
    'phase': _Input(doc='Offset of the color palette.', default_value='0.0'),
}


def define_function(sh):
    """Define the Julia set function in the generator *sh*.

    The body is a hot-pink placeholder.
    """
    with sh.function(FUNC_NAME)(
        position=sh.Float3,
        cx=sh.Float,
        cy=sh.Float,
        scale=sh.Float,
        max_iterations=sh.Int,
        phase=sh.Float,
        out_=sh.Out(sh.RgbF),
    ):
        sh.out_ = sh.RgbF((1.0, 0.0, 0.5))


def generate(ctx: GeneratorContext):
    """Generate the Julia set source-code node into *ctx*.

    If *ctx* is ``impl_only``, the implementation references the
    ``ND_julia_set`` nodedef generated by another context.
    """
    define_function(ctx._sh)
    nodedef = ctx.add_node_impl(
        func_name=FUNC_NAME,
        mx_doc_string='Metashade Julia set',
        nodedef_name=NODEDEF_NAME,
        input_metadata=_INPUTS,
    )
    if nodedef is None:
        return

    for name, metadata in _INPUTS.items():
        mx_input = nodedef.getInput(name)
        if metadata.default_value:
            mx_input.setValueString(metadata.default_value)
        if metadata.defaultgeomprop:
            mx_input.setDefaultGeomPropString(metadata.defaultgeomprop)

    # MaterialX binds source-code outputs by position, so the nodedef can
    # use the conventional name even though ``out`` is a GLSL keyword.
    mx_output = nodedef.getOutput('out_')
    mx_output.setName('out')
    mx_output.setDocString('Color of the Julia set.')
